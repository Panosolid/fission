import { launch } from "./browser.mjs";
import { preview } from "vite";
const server = await preview({ preview: { port: 4197, strictPort: true }, logLevel: "error" });
const browser = await launch();
const page = await (await browser.newContext({ viewport: { width: 1280, height: 800 } })).newPage();
await page.addInitScript(() => indexedDB.deleteDatabase("fission"));
await page.goto("http://localhost:4197/#design");
await page.waitForFunction(() => document.querySelector("#volume")?.textContent === "24,000 mm³");
await page.click("#create-sketch");
await page.click("#sketch-plane-XY");
await page.waitForFunction(() => document.querySelector("#viewport").dataset.sketching === "true");
const y = async () => (await page.locator("#sketch-extrude").boundingBox()).y;
const before = await y();
await page.focus("#sketch-grid");
await page.keyboard.press("Control+A");
await page.keyboard.press(process.env.KEY || "e");
console.log("grid value", JSON.stringify(await page.inputValue("#sketch-grid")));
await page.click("#sketch-extrude");
await page.waitForTimeout(800);
console.log("extrude button y before/after", before, await y().catch(() => "gone"));
console.log("extrude panel visible", await page.isVisible("#extrude-panel"), "status", await page.textContent("#extrude-status").catch(() => "(none)"));
console.log("grid error", await page.textContent("#sketch-grid-error").catch(() => "(none)"));
await browser.close(); await server.close();
